    # --- Reserved for v1.2: defined, never emitted by the MVP --------------
    PACKAGE_REVOKED = "PACKAGE_REVOKED"
    SENSITIVE_ARTEFACT_QUARANTINED = "SENSITIVE_ARTEFACT_QUARANTINED"

    # --- Kernel extensions (§27 says "at least") ----------------------------
    CONFIG_WEAKENING_REJECTED = "CONFIG_WEAKENING_REJECTED"
