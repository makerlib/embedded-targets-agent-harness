    BASELINE_FAILED = "BASELINE_FAILED"
    CONTRACT_HASH_MISMATCH = "CONTRACT_HASH_MISMATCH"
    CONTRACT_MUTATED_AFTER_LOCK = "CONTRACT_MUTATED_AFTER_LOCK"
    PATH_OUTSIDE_SCOPE = "PATH_OUTSIDE_SCOPE"
    PROTECTED_PATH_CHANGED = "PROTECTED_PATH_CHANGED"
    PACKAGE_NOT_FOUND = "PACKAGE_NOT_FOUND"
    PACKAGE_VERSION_CONFLICT = "PACKAGE_VERSION_CONFLICT"
    PACKAGE_DEPENDENCY_CYCLE = "PACKAGE_DEPENDENCY_CYCLE"
    PACKAGE_DIGEST_MISMATCH = "PACKAGE_DIGEST_MISMATCH"
    TOOL_NOT_REGISTERED = "TOOL_NOT_REGISTERED"
    TOOL_PERMISSION_DENIED = "TOOL_PERMISSION_DENIED"
    APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
    APPROVAL_INVALID = "APPROVAL_INVALID"
    LEASE_ALREADY_HELD = "LEASE_ALREADY_HELD"
    LEASE_STALE = "LEASE_STALE"
    WORKFLOW_REVISION_CONFLICT = "WORKFLOW_REVISION_CONFLICT"
    TRANSITION_NOT_ALLOWED = "TRANSITION_NOT_ALLOWED"
    HANDOFF_INVALID = "HANDOFF_INVALID"
    HANDOFF_DIFF_MISMATCH = "HANDOFF_DIFF_MISMATCH"
    PLAN_COVERAGE_INCOMPLETE = "PLAN_COVERAGE_INCOMPLETE"
    GATE_PRECONDITION_FAILED = "GATE_PRECONDITION_FAILED"
    GATE_TIMEOUT = "GATE_TIMEOUT"
    GATE_EVIDENCE_MISSING = "GATE_EVIDENCE_MISSING"
    RETRY_LIMIT_EXCEEDED = "RETRY_LIMIT_EXCEEDED"
    REWORK_LIMIT_EXCEEDED = "REWORK_LIMIT_EXCEEDED"
