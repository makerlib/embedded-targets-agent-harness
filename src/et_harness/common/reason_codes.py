    PROFILE_ESCALATION_REQUIRED = "PROFILE_ESCALATION_REQUIRED"
    ENFORCEMENT_TIER_INSUFFICIENT = "ENFORCEMENT_TIER_INSUFFICIENT"
    HOOK_DECISION_TIMEOUT = "HOOK_DECISION_TIMEOUT"
    STATE_TAMPER_DETECTED = "STATE_TAMPER_DETECTED"
    PROJECTION_DRIFT = "PROJECTION_DRIFT"
    QE_TEST_MODIFIED = "QE_TEST_MODIFIED"
    BASELINE_TESTS_NOT_FAILING = "BASELINE_TESTS_NOT_FAILING"
